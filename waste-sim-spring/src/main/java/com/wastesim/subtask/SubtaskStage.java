package com.wastesim.subtask;

/**
 * 서브태스크가 언제 채워지는가.
 *
 * <p>세트는 50개를 생략 없이 유지하지만, 그 50개가 전부 "사용자에게 던지는 질문"인 것은
 * 아니다. 마지막 셋(입력 요약 확인·시나리오 미리보기 확인·실행 승인)은 <b>조립된 시나리오가
 * 있어야</b> 보여줄 수 있어서, 수집 도중에 물으면 보여줄 내용이 없는 빈 질문이 된다.
 * 그래서 그 셋은 미리보기 화면이 대신 채운다.
 */
public enum SubtaskStage {

    /** 사용자에게 질문으로 던져 답을 받는다(ST-001~047). */
    COLLECT,

    /**
     * 조립 뒤 미리보기 화면이 대신 채운다(ST-048~050).
     *
     * <p>화면에는 실행 승인만 노출하고, 요약·시나리오 확인은 그 화면을 본 것으로 갈음한다 —
     * 같은 내용을 세 번 확인시키면 사용자는 세 번 다 읽지 않는다.
     */
    CONFIRM
}
