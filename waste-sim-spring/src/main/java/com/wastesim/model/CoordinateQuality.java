package com.wastesim.model;

/**
 * 이 실행이 쓴 좌표가 어디서 왔는가 — <b>데이터의 속성</b>이며 계산 방식과는 다른 축이다.
 *
 * <p>결과에 이 값을 함께 실어 보낸다. 같은 숫자라도 현장 GPS로 계산한 38분과 구역 좌표로
 * 근사한 38분은 다른 것이고, 표시가 없으면 읽는 사람이 그 차이를 알 수 없다.
 *
 * <p>{@link com.wastesim.model.TravelTimeMode}와 섞지 않는다. 모드는 "무엇으로 계산하는가",
 * 이 값은 "그 입력이 얼마나 실제인가"다. 한 enum에 합치면 축이 뒤섞인다 —
 * {@code Node_A}가 교통 구역과 수거 지점을 동시에 뜻하던 것과 같은 종류의 혼동이다.
 */
public enum CoordinateQuality {

    /**
     * 좌표를 쓰지 않는 계산. 상수 이동시간 모드가 여기다.
     *
     * <p>경고가 없다 — 좌표를 쓰지 않았으니 좌표 품질에 대해 경고할 것이 없다. 이동시간이
     * 상수라는 사실은 모드 이름이 이미 말하고 있고, 경고를 남발하면 정작 읽어야 할 경고가
     * 묻힌다.
     */
    NOT_USED("좌표 미사용", null),

    /** 현장에서 측정한 수거 지점 GPS. 최종 검증·운영에 쓸 수 있는 유일한 수준. */
    MEASURED_SITE("현장 실측", null),   // 좌표를 현장에서 잰 경우만. 도로 시간의 출처와는 별개다.

    /** 건물·공동배출장소 주소를 지오코딩한 좌표. 운영 후보로 쓸 만하지만 실측은 아니다. */
    ADDRESS_GEOCODED("주소 지오코딩",
            "수거 지점 주소를 지오코딩한 좌표입니다. 현장 실측이 아니므로 지점별 오차가 있습니다."),

    /**
     * 수거 지점 좌표 없이 <b>교통 구역</b>으로 근사한 것. 지금 당장 실행 가능한 수준이다.
     *
     * <p>구역이 바뀌는 이동만 OSRM 산출 자유주행시간을 쓰고, 같은 구역 안의 이동은 평균으로
     * 대체한다. 그래서 지점 단위 경로 최적화 결론에는 쓸 수 없다 — 같은 구역 안에서 어느
     * 순서로 도는지가 결과에 반영되지 않기 때문이다.
     */
    TRAFFIC_ZONE_PROXY("교통 구역 근사",
            "실제 수거 지점 좌표를 쓰지 않았습니다. 교통 구역 4곳 사이를 OSRM이 도로망에서 "
                    + "산출한 자유주행시간으로 근사한 값이며(현장 주행 기록이 아닙니다), "
                    + "같은 구역 안의 이동은 평균으로 대체했습니다. 지점 단위 경로 비교에는 "
                    + "쓸 수 없습니다."),

    /** 구역 안 도로에 생성한 가상 지점. 단일 값이 아니라 범위를 얻는 데 쓴다. */
    SYNTHETIC("가상 지점",
            "구역 안 도로에 생성한 가상 좌표입니다. 단일 값이 아니라 범위로 읽어야 합니다.");

    public final String labelKo;
    /** 결과에 함께 나가는 경고. {@code null}이면 경고할 것이 없다. */
    public final String warning;

    CoordinateQuality(String labelKo, String warning) {
        this.labelKo = labelKo;
        this.warning = warning;
    }

    public boolean hasWarning() {
        return warning != null;
    }
}
