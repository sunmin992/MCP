package com.wastesim.template;

/**
 * 이 가지가 살아 있는가.
 *
 * <p>결정기록(ledger) 패키지에서 왔다. 그 subsystem 은 프로덕션에서 닿지 않게 되어
 * 지웠는데, 이 enum 만은 생성 조건이 쓰고 있었다 — 세 갈래 판정은 결정기록이 아니라
 * 서브태스크 생성의 개념이다.
 *
 * <p><b>왜 참·거짓이 아니라 셋인가</b>: 조건이 의존하는 값이 아직 없을 때 거짓을 돌려주면,
 * "아직 모른다"와 "필요 없다"가 같은 답이 된다. 그러면 아무 답도 하지 않은 실행이 모든
 * 조건부 가지를 건너뛰고 통과한다.
 */
public enum Activation {

    /** 살아 있다. 이 가지의 필수값을 물어야 한다. */
    ACTIVE,

    /** 죽었다. 이 가지의 필수값은 해당 없음으로 확정할 수 있다. */
    INACTIVE,

    /** 판단할 값이 아직 없다. <b>비활성으로 접지 않는다.</b> */
    UNKNOWN
}
